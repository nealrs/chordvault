function lowestFret(frets: Fret[]): number {
  const played = frets.filter((v): v is number => v !== null && v > 0);
  return played.length ? Math.min(...played) : 0;
}

/** Parses "F#m7", "Bb", "G/B", "C#dim7", etc. into { root, quality } or null if unsupported. */
function parseChordName(name: string): { root: string; quality: Quality } | null {
  const m = name.trim().match(/^([A-G])([#b]?)([^/]*)(?:\/.*)?$/);
  if (!m) return null;
  const root = m[1] + m[2];
  if (!(root in ROOT_SEMITONE)) return null;
  const rest = m[3];

  const quality = QUALITY_MAP[rest];
  if (!quality) return null;
  return { root, quality };
}

export function getChordShape(chordName: string): ChordShape | null {
  const parsed = parseChordName(chordName);
  if (!parsed) return null;
  const { root, quality } = parsed;

  const canonicalRoot = SEMITONE_TO_ROOT[ROOT_SEMITONE[root]];
  const frets = SHAPES[`${canonicalRoot}:${quality}`];
  if (!frets) return null;

  return { frets, baseFret: lowestFret(frets) };
}
